-- Repair live production drift discovered during controlled Telegram acceptance.
-- Keep this migration idempotent: it is safe whether 0003 ran fully, partially,
-- or was incorrectly recorded while the relation is absent.

CREATE TABLE IF NOT EXISTS pending_calendar_intents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope_type TEXT NOT NULL CHECK (scope_type IN ('personal', 'group')),
    scope_id TEXT NOT NULL,
    actor_user_id TEXT NOT NULL,
    source_event_id TEXT NOT NULL UNIQUE,
    payload JSONB NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'completed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_pending_calendar_intents_lookup
    ON pending_calendar_intents(scope_type, scope_id, actor_user_id, created_at DESC)
    WHERE status='pending';
